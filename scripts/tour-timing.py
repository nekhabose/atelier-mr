"""Time the guided tour to the narration.

Reads the length of each recorded line (docs/video/vo/lengths.json, written by
split-voice.py) and lays the lines end to end with a short breath between them
(a little longer where the picture needs a moment: the room reveal, the mark,
the fabric, the boutique verdict). Writes:

  src/atelier/tour-timing.ts   when each line starts and how long it is (the
                               tour places its scenes and actions from these)
  scripts/narration.txt        the same start times, for the mixer

    python3 scripts/tour-timing.py

Without recordings it uses the reading-time budgets already in narration.txt.
"""
import json
import os
import re
import subprocess

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FIRST = 0.6
BREATH = 0.5
# Extra hold after a line (0-based) where the picture needs a moment.
HOLD = {1: 0.7, 5: 1.0, 7: 1.0, 10: 0.8}
# Words the tour acts on (0-based line: words). Each gets its time in the line.
TARGETS = {
    2: ['dresses'],
    3: ['dressier'],
    4: ['dress'],
    5: ['knee'],
    6: ['pull'],
    7: ['satin', 'silk'],
    8: ['lay'],
    9: ['builds'],
    10: ['counts'],
    11: ['sit'],
    13: ['Get', 'Open'],
}


def syllables(word):
    w = word.lower()
    g = len(re.findall(r'[aeiouy]+', w))
    if w.endswith('e') and not w.endswith(('le', 'ee')) and g > 1:
        g -= 1
    return max(1, g)


def beats(path):
    """Syllable-like beats (seconds): peaks of the speech energy envelope."""
    raw = subprocess.run(['ffmpeg', '-loglevel', 'error', '-i', path, '-ac', '1', '-ar', '16000', '-f', 'f32le', '-'],
                         capture_output=True, check=True).stdout
    x = np.frombuffer(raw, dtype=np.float32)
    hop = 160  # 10 ms
    e = np.sqrt(np.convolve(x[: len(x) // hop * hop].reshape(-1, hop).__pow__(2).mean(axis=1), np.ones(5) / 5, mode='same'))
    thr = max(e.max() * 0.18, np.median(e) * 2)
    out, last = [], -99
    for i in range(1, len(e) - 1):
        if e[i] > thr and e[i] >= e[i - 1] and e[i] > e[i + 1] and i - last >= 12:
            if last < 0 or e[last:i].min() < e[i] * 0.75:
                out.append(i / 100)
                last = i
    return out


def word_times(text, path, length):
    """When each target word starts in its clip: the beat at the word's place
    among the line's syllables (falls back to its share of the line)."""
    words = re.findall(r"[A-Za-z']+", text)
    counts = [syllables(w) for w in words]
    total = sum(counts)
    b = beats(path) if os.path.exists(path) else []
    out = {}
    for k, w in enumerate(words):
        before = sum(counts[:k])
        if b:
            idx = min(len(b) - 1, int(round(before / total * len(b))))
            out.setdefault(w.lower(), round(b[idx], 2))
        else:
            out.setdefault(w.lower(), round(before / total * length, 2))
    return out

narration = os.path.join(ROOT, 'scripts', 'narration.txt')
with open(narration, encoding='utf-8') as f:
    rows = [l.rstrip('\n') for l in f]
header = [r for r in rows if r.startswith('#') or not r.strip()]
lines = [r.split('|', 1) for r in rows if r.strip() and not r.startswith('#')]

lengths_path = os.path.join(ROOT, 'docs', 'video', 'vo', 'lengths.json')
known_words = {}
if os.path.exists(lengths_path):
    with open(lengths_path) as f:
        meta = json.load(f)
    lengths = meta['lengths']
    # Lines spoken phrase by phrase (the cloned voice) come with exact word times.
    known_words = meta.get('words', {})
    source = 'the cloned narration' if meta.get('found_by') == 'clone' else 'your recorded lines'
else:
    starts = [float(t) for t, _ in lines]
    lengths = [round(b - a - 0.6, 2) for a, b in zip(starts, starts[1:])] + [5.5]
    source = 'reading-time budgets'
assert len(lengths) == len(lines), 'one length per line'

starts = []
t = FIRST
for i, d in enumerate(lengths):
    starts.append(round(t, 2))
    t += d + (HOLD.get(i, BREATH) if i < len(lengths) - 1 else 0)

with open(narration, 'w', encoding='utf-8') as f:
    f.write('\n'.join(h for h in header if h.startswith('#')) + '\n')
    for s, (_, text) in zip(starts, lines):
        f.write(f'{s}|{text}\n')

word_at = dict(known_words)
for i, ws in TARGETS.items():
    if all(f'{i}:{w.lower()}' in word_at for w in ws):
        continue
    found = word_times(lines[i][1], os.path.join(ROOT, 'docs', 'video', 'vo', f'l{i}.wav'), lengths[i])
    for w in ws:
        if w.lower() in found:
            word_at[f'{i}:{w.lower()}'] = found[w.lower()]

ts = os.path.join(ROOT, 'src', 'atelier', 'tour-timing.ts')
with open(ts, 'w') as f:
    f.write('/**\n * When each narration line of the guided tour starts, and how long it is\n')
    f.write(f' * (seconds), from {source}. Generated by scripts/tour-timing.py.\n */\n')
    f.write(f'export const LINE_START = {json.dumps(starts)};\n')
    f.write(f'export const LINE_LENGTH = {json.dumps([round(d, 2) for d in lengths])};\n')
    f.write('/** Seconds into a line when a word the tour acts on is spoken ("line:word"). */\n')
    f.write(f'export const WORD_AT: Record<string, number> = {json.dumps(word_at)};\n')
    f.write('/** What is said: the captions show these words. */\n')
    f.write(f'export const LINE_TEXT = {json.dumps([t for _, t in lines], ensure_ascii=False, indent=2)};\n')

end = starts[-1] + lengths[-1]
print(f'{len(lines)} lines from {source}; narration ends at {end:.1f} s')
