"""Time the guided tour to the narration.

Reads the length of each recorded line (docs/video/vo/lengths.json, written by
split-voice.py) and lays the lines end to end with a short breath between them
(a little longer where the picture needs a moment: the room reveal, the mark,
the fabric, the boutique verdict). Writes:

  src/atelier/tour-timing.ts   when each line starts and how long it is (the
                               tour places its scenes and actions from these)
  scripts/narration.txt        the same start times, for the mixer

    python3 scripts/tour-timing.py

Without recordings it uses the reading-time budgets already in narration.txt.
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FIRST = 0.6
BREATH = 0.5
# Extra hold after a line (0-based) where the picture needs a moment.
HOLD = {1: 0.7, 5: 1.0, 7: 1.0, 10: 0.8}

narration = os.path.join(ROOT, 'scripts', 'narration.txt')
with open(narration, encoding='utf-8') as f:
    rows = [l.rstrip('\n') for l in f]
header = [r for r in rows if r.startswith('#') or not r.strip()]
lines = [r.split('|', 1) for r in rows if r.strip() and not r.startswith('#')]

lengths_path = os.path.join(ROOT, 'docs', 'video', 'vo', 'lengths.json')
if os.path.exists(lengths_path):
    with open(lengths_path) as f:
        lengths = json.load(f)['lengths']
    source = 'your recorded lines'
else:
    starts = [float(t) for t, _ in lines]
    lengths = [round(b - a - 0.6, 2) for a, b in zip(starts, starts[1:])] + [5.5]
    source = 'reading-time budgets'
assert len(lengths) == len(lines), 'one length per line'

starts = []
t = FIRST
for i, d in enumerate(lengths):
    starts.append(round(t, 2))
    t += d + (HOLD.get(i, BREATH) if i < len(lengths) - 1 else 0)

with open(narration, 'w', encoding='utf-8') as f:
    f.write('\n'.join(h for h in header if h.startswith('#')) + '\n')
    for s, (_, text) in zip(starts, lines):
        f.write(f'{s}|{text}\n')

ts = os.path.join(ROOT, 'src', 'atelier', 'tour-timing.ts')
with open(ts, 'w') as f:
    f.write('/**\n * When each narration line of the guided tour starts, and how long it is\n')
    f.write(f' * (seconds), from {source}. Generated by scripts/tour-timing.py.\n */\n')
    f.write(f'export const LINE_START = {json.dumps(starts)};\n')
    f.write(f'export const LINE_LENGTH = {json.dumps([round(d, 2) for d in lengths])};\n')

end = starts[-1] + lengths[-1]
print(f'{len(lines)} lines from {source}; narration ends at {end:.1f} s')
